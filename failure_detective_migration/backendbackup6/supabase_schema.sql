-- Run this once in Supabase Dashboard > SQL Editor.
-- Backend-only access: keep the service_role key exclusively in Render secrets.
create table if not exists public.diagnostic_messages (
    id bigint generated by default as identity primary key,
    session_id uuid not null,
    role text not null check (role in ('user', 'assistant')),
    content text not null,
    metadata jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now()
);

create index if not exists diagnostic_messages_session_created_idx
    on public.diagnostic_messages (session_id, created_at desc);

alter table public.diagnostic_messages enable row level security;
